"""
Delve Chart screen — PoE 'Subterranean Chart'-style
map shown before entering the delve (and as an in-delve minimap overlay).

Renders the persistent depth-row chart graph from core/delve_gen.py:
- tall vertical winding tunnel network, scrolled downward as depth increases
- biome-colored veins per depth zone, dim gray unexplored tunnels
- node icons + fog-of-war for unrevealed nodes
- golden route line for the current/planned path
- hover tooltip (node name, biome, DEPTH, MONSTER LEVEL, reward hint)
- right-edge vertical depth gauge, top-left title banner, a BEST DEPTH
  readout on the screen frame (outside the modal) and a RETURN TO HUB button
  at the modal's bottom-right

Input: mouse-wheel zoom (opens at ZOOM_DEFAULT — three wheel-notches
zoomed out from the maximum, centred on the current node), left-drag pan (click without drag = select), Escape closes.
Fully data-driven — no game-object coupling. Node positions come from
core/delve_gen.py (`layout_positions`); this module only projects them.
"""

import math

import pyray as rl

from config import ASSETS
from ui import fonts
import core.delve_gen as delve_gen
from systems import input as inp

ZOOM_MIN = 0.45
ZOOM_MAX = 3.2
# Opens three wheel-notches zoomed OUT from the old max default (owner
# ruling 2026-10-07): each wheel step is ×0.85, so 0.85³ of the max.
ZOOM_DEFAULT = round(ZOOM_MAX * 0.85 ** 3, 3)

_FOG_COL = rl.Color(58, 62, 74, 255)
_EXPLORED_COL = rl.Color(150, 155, 170, 255)
_ROUTE_COL = rl.Color(255, 205, 80, 255)
_BANNER_BG = rl.Color(0, 0, 0, 0x99)
_TOOLTIP_BG = rl.Color(8, 10, 18, 245)
_TOOLTIP_BORDER = rl.Color(90, 74, 28, 255)   # worn gold frame
_HEADER_BG = rl.Color(58, 46, 18, 240)

# Reward-item icon cache (loaded once, kept for the session — a handful of
# small 32x32 textures; organs are the only node drop ids today)
_ICON_CACHE = {}
_BTN1_TEX = None
_BTN1_DOWN_TEX = None


def _reward_icon(item_id):
    """Texture for a node reward item id, or None when unavailable."""
    if item_id in _ICON_CACHE:
        return _ICON_CACHE[item_id]
    tex = None
    try:
        from systems.items import ITEMS
        img = (ITEMS.get(item_id) or {}).get('img')
        if img:
            import os
            path = os.path.join(ASSETS, *img.split('/'))
            if os.path.exists(path):
                tex = rl.load_texture(path)
    except Exception:
        tex = None
    _ICON_CACHE[item_id] = tex
    return tex


def _enter_button_tex(pressed=False):
    """Kit Button#1 grunge art (Status=Pressed / Red_Hover), loaded once.
    Falls back to the legacy ui/button_1 art when the kit is missing."""
    global _BTN1_TEX, _BTN1_DOWN_TEX
    import os
    if pressed:
        if _BTN1_DOWN_TEX is None:
            path = os.path.join(ASSETS, *'gui\\Button\\Button#1\\Status=Pressed.png'.split('\\'))
            _BTN1_DOWN_TEX = (rl.load_texture(path)
                              if os.path.exists(path)
                              else rl.load_texture(os.path.join(ASSETS, 'ui', 'button_1_pressed.png')))
        return _BTN1_DOWN_TEX
    if _BTN1_TEX is None:
        path = os.path.join(ASSETS, *'gui\\Button\\Button#1\\Status=Red_Hover.png'.split('\\'))
        _BTN1_TEX = (rl.load_texture(path) if os.path.exists(path)
                     else rl.load_texture(os.path.join(ASSETS, 'ui', 'button_1.png')))
    return _BTN1_TEX


def node_world_pos(node):
    """Chart-world position of a node. Positions are generated by
    core/delve_gen.py (see layout_positions); this only falls back to the
    same formula for nodes that predate the stored coordinates."""
    px = node.get('px')
    py = node.get('py')
    if px is None or py is None:
        px, py = delve_gen.node_pos(node.get('depth', 1), node.get('col', 0.0))
    return px, py


def _node_screen_pos(node, cam_x, cam_y, zoom, cw, ch):
    """Chart-world position -> screen. Vertical layout: depth grows down."""
    cx, cy = node_world_pos(node)
    sx = (cx - cam_x) * zoom + cw // 2
    sy = (cy - cam_y) * zoom + ch // 2
    return sx, sy


class DelveChartScreen:
    """Zoomable/pannable delve chart renderer with fog-of-war and selection."""

    def __init__(self, game):
        self._game = game
        self.chart = None            # {'graph','visited','looted','checkpoints','route','charges'}
        self.selectable_ids = ()     # node ids the player may descend to
        self.on_select = None        # callable(node_id)
        self.closable = True
        self.title = 'Anima Chart'
        self.zoom = ZOOM_DEFAULT
        self.cam_x = 0.0
        self.cam_y = 0.0
        self._drag_start = None      # (mx, my) when drag began
        self._dragged = False
        self._hover_id = None
        self._return_btn = None
        self._tooltip_btn = None     # ('ENTER' button rect, node id) from draw

    def _reset_drag(self):
        """Cancel any panning gesture (including a release that missed a tick)."""
        self._drag_start = None
        self._dragged = False

    # ── lifecycle ────────────────────────────────────────────────────

    def open(self, chart, selectable_ids=(), on_select=None,
             title='Anima Chart', closable=True):
        self.chart = chart or self._empty_chart()
        self.selectable_ids = tuple(selectable_ids)
        self.on_select = on_select
        self.title = title
        self.closable = closable
        # Default opens three wheel-notches zoomed out (owner 2026-10-07) —
        # an overview of the surrounding rows like PoE's Subterranean Chart.
        self.zoom = ZOOM_DEFAULT
        self._hover_id = None
        self._reset_drag()
        self._centre_on_current()

    def _centre_on_current(self):
        """Centre the camera on the node the player is standing on (or, with
        no current node, the deepest cleared one). Chart coords are
        generator-owned, so re-centring never has to guess a layout."""
        graph = (self.chart or {}).get('graph', {})
        nodes = graph.get('nodes', {})
        node = nodes.get((self.chart or {}).get('current_node_id'))
        if node is None:
            visited = [nid for nid in (self.chart or {}).get('visited', [])
                       if nid in nodes]
            if visited:
                node = max((nodes[nid] for nid in visited),
                           key=lambda n: n['depth'])
        if node is None:
            self.cam_x = self.cam_y = 0.0
        else:
            self.cam_x, self.cam_y = node_world_pos(node)

    @staticmethod
    def _empty_chart():
        graph = delve_gen.init_delve(0)
        return {'graph': graph, 'visited': [graph['start_node_id']],
                'looted': [], 'checkpoints': [], 'route': []}

    # ── update ───────────────────────────────────────────────────────

    def update(self, dt, origin=(0.0, 0.0), view=None):
        """Handle input. Returns 'close', ('select', node_id) or None.

        `origin`/`view` confine the chart to a popup panel: mouse coords are
        translated into canvas space and node interaction is ignored while
        the cursor is outside the view rect. Defaults keep fullscreen mode.
        """
        cw, ch = rl.get_screen_width(), rl.get_screen_height()
        ox, oy = int(origin[0]), int(origin[1])
        vw, vh = (int(view[0]), int(view[1])) if view else (cw, ch)
        mx, my = rl.get_mouse_x() - ox, rl.get_mouse_y() - oy
        inside = 0 <= mx < vw and 0 <= my < vh

        # Always poll both edges, including while outside the popup.  The
        # press edge starts a gesture only inside, but a release can happen
        # after the cursor leaves; skipping the poll leaves the input edge
        # latched and the next tick can start/stop panning from stale state.
        left_released = inp.mouse_released('delve_chart.drag', rl.MOUSE_BUTTON_LEFT)
        left_down = inp.mouse_pressed('delve_chart.drag', rl.MOUSE_BUTTON_LEFT)
        if left_released or not rl.is_window_focused():
            self._reset_drag()

        # Zoom (wheel), centred on cursor — only over the chart surface
        wheel = rl.get_mouse_wheel_move() if inside else 0.0
        if wheel != 0.0:
            new_zoom = max(ZOOM_MIN, min(ZOOM_MAX, self.zoom * (1.0 + wheel * 0.15)))
            wx = (mx - vw // 2) / self.zoom + self.cam_x
            wy = (my - vh // 2) / self.zoom + self.cam_y
            self.zoom = new_zoom
            self.cam_x = wx - (mx - vw // 2) / self.zoom
            self.cam_y = wy - (my - vh // 2) / self.zoom

        # Pan by dragging — drag only starts on empty space. Pressing a
        # selectable node (or the tooltip ENTER button) descends instantly
        # on press; pressing a non-selectable node is a dead click — the
        # map must never pan under an intended node interaction.
        if inside and left_down:
            # RETURN TO HUB sits above everything else in the modal. The rect
            # only exists while the modal has been drawn (popup mode).
            ret = self._return_btn
            if ret is not None and rl.check_collision_point_rec(
                    rl.Vector2(float(mx), float(my)), ret):
                self._reset_drag()
                return ('return_hub', None)
            btn = self._tooltip_btn
            if (btn is not None and btn[1] in self.selectable_ids
                    and rl.check_collision_point_rec(
                        rl.Vector2(float(mx), float(my)), btn[0])):
                self._reset_drag()
                return ('select', btn[1])
            nid = self._node_at(mx, my, vw, vh)
            if nid is not None and nid in self.selectable_ids and self.on_select:
                self._reset_drag()
                return ('select', nid)
            if nid is None:                      # empty space → pan
                self._drag_start = (mx, my)
                self._dragged = False
            # node press on a non-selectable node → dead click (no drag)
        elif self._drag_start is not None:
            dx, dy = mx - self._drag_start[0], my - self._drag_start[1]
            if abs(dx) > 4 or abs(dy) > 4:
                self._dragged = True
                self.cam_x -= dx / self.zoom
                self.cam_y -= dy / self.zoom
                self._drag_start = (mx, my)
        if self.closable and inp.key_pressed('delve_chart.close', rl.KEY_ESCAPE):
            self._reset_drag()
            return 'close'

        self._hover_id = self._node_at(mx, my, vw, vh) if inside else None
        return None

    def _node_at(self, mx, my, cw, ch):
        graph = self.chart.get('graph', {}) if self.chart else {}
        best, best_dist = None, 0.0
        for node in graph.get('nodes', {}).values():
            if node.get('dead_end'):
                continue
            sx, sy = _node_screen_pos(node, self.cam_x, self.cam_y,
                                      self.zoom, cw, ch)
            # hit radius follows the (big) reward icon, not a fixed 22px
            radius = int((8 if node['type'] in ('checkpoint', 'boss') else 6)
                         * self.zoom)
            hit = max(22.0, radius * 3.1)
            d = math.hypot(sx - mx, sy - my)
            if d < hit and (best is None or d < best_dist):
                best, best_dist = node['id'], d
        return best

    # ── draw ─────────────────────────────────────────────────────────

    def draw(self, cw, ch, origin=(0.0, 0.0), view=None):
        """Render the chart. `origin`/`view` embed it in a popup panel
        (scissor-clipped onto the panel surface, no background clear);
        defaults keep the fullscreen behaviour (in-delve minimap)."""
        if self.chart is None:
            return
        self._ox = int(origin[0])
        self._oy = int(origin[1])
        vw, vh = (int(view[0]), int(view[1])) if view else (cw, ch)
        self._popup = view is not None
        if self._popup:
            rl.begin_scissor_mode(self._ox, self._oy, vw, vh)

        graph = self.chart['graph']
        revealed = self._revealed_set()

        # Camera is centred on the current node in open(); nothing to derive
        # from the visited list here any more.
        self._draw_background(vw, vh, graph, revealed)
        self._draw_edges(vw, vh, graph, revealed)
        self._draw_route(vw, vh, graph)
        self._draw_nodes(vw, vh, graph, revealed)
        if not self._popup:
            self._draw_title(cw)
        # BEST DEPTH lives on the screen frame, never inside the modal.
        self._draw_best_depth(cw, below_title=not self._popup)
        if self._popup:
            self._draw_return_button(vw, vh)
        if not self._popup:
            self._draw_depth_gauge(ch, graph)
        self._draw_tooltip(vw, vh, graph)

        if self._popup:
            rl.end_scissor_mode()

    def _nsp(self, node, vw, vh):
        """Node screen position in canvas space + popup origin."""
        sx, sy = _node_screen_pos(node, self.cam_x, self.cam_y,
                                  self.zoom, vw, vh)
        return sx + self._ox, sy + self._oy

    def _draw_background(self, vw, vh, graph, visited):
        if not self._popup:
            rl.clear_background(rl.Color(10, 10, 16, 255))
        # Biome-colored patches per depth band (§9A-7)
        max_depth = max((n['depth'] for n in graph['nodes'].values()), default=1)
        for zone_start in range(1, max_depth + 1, delve_gen.ZONE_PERIOD):
            zone = delve_gen.zone_for_depth(zone_start)
            col = zone['color']
            zy1 = (zone_start - 1) * delve_gen.CHART_ROW_SPACING
            zy2 = (zone_start + delve_gen.ZONE_PERIOD - 1) * delve_gen.CHART_ROW_SPACING
            y1 = (zy1 - self.cam_y) * self.zoom + vh // 2 + self._oy
            y2 = (zy2 - self.cam_y) * self.zoom + vh // 2 + self._oy
            if y2 < self._oy - 50 or y1 > self._oy + vh + 50:
                continue
            rl.draw_rectangle(self._ox, int(y1), vw, int(y2 - y1),
                              rl.Color(col[0], col[1], col[2], 60))

    def _draw_edges(self, vw, vh, graph, revealed):
        for parent_id, child_id in graph['edges']:
            parent = graph['nodes'].get(parent_id)
            child = graph['nodes'].get(child_id)
            if parent is None or child is None:
                continue
            p = self._nsp(parent, vw, vh)
            c = self._nsp(child, vw, vh)
            if c[1] < self._oy - 80 or p[1] > self._oy + vh + 80:
                continue
            known = parent_id in revealed or child_id in revealed
            zone = delve_gen.zone_for_depth(child['depth'])
            accent = zone['accent']
            if known:
                col = rl.Color(accent[0], accent[1], accent[2], 200)
                thick = max(2, int(5 * self.zoom))
            else:
                col = _FOG_COL
                thick = max(1, int(3 * self.zoom))
            rl.draw_line(int(p[0]), int(p[1]), int(c[0]), int(c[1]), col)
            if known:
                rl.draw_line(int(p[0]), int(p[1]) + thick, int(c[0]),
                             int(c[1]) + thick,
                             rl.Color(accent[0], accent[1], accent[2], 70))

    def _draw_route(self, vw, vh, graph):
        route = [nid for nid in self.chart.get('route', []) if nid in graph['nodes']]
        if len(route) < 2:
            return
        points = [self._nsp(graph['nodes'][nid], vw, vh) for nid in route]
        for i in range(len(points) - 1):
            rl.draw_line_ex(rl.Vector2(points[i][0], points[i][1]),
                            rl.Vector2(points[i + 1][0], points[i + 1][1]),
                            max(2.0, 3.5 * self.zoom), _ROUTE_COL)

    def _draw_nodes(self, vw, vh, graph, revealed):
        current_id = self.chart.get('current_node_id')
        for node in graph['nodes'].values():
            if node.get('dead_end') and node['id'] not in revealed:
                continue
            sx, sy = self._nsp(node, vw, vh)
            if sy < self._oy - 40 or sy > self._oy + vh + 40:
                continue
            known = node['id'] in revealed
            selectable = node['id'] in self.selectable_ids
            color = (delve_gen.NODE_COLORS.get(node['type'], (200, 200, 200))
                     if known else (90, 94, 108))
            # Small ring, BIG icon — the reward icon overflows the circle
            # on purpose (owner ruling 2026-10-07, §26).
            radius = int((8 if node['type'] in ('checkpoint', 'boss') else 6)
                         * self.zoom)
            ix, iy = int(sx), int(sy)      # pyray draw_circle requires ints
            if node['id'] == current_id:
                rl.draw_circle(ix, iy, radius + 5, rl.Color(255, 255, 255, 90))
            if selectable:
                rl.draw_circle(ix, iy, radius + 4, _ROUTE_COL)
            rl.draw_circle(ix, iy, radius,
                           rl.Color(color[0], color[1], color[2], 255))
            # Reward item icon for revealed nodes (§9A fog-of-war hides
            # icons); glyph fallback for no-reward nodes, dimmed when looted
            if known:
                looted = node['id'] in self.chart.get('looted', [])
                icon = None
                rewards = node.get('rewards') or []
                if rewards:
                    icon = _reward_icon(rewards[0]['item'])
                if icon and icon.id > 0:
                    # 2× bigger than before (owner 2026-10-07): the item
                    # icon is ~3.1× the circle diameter — PoE-style, the
                    # icon IS the node.
                    isz = max(6, int(radius * 2 * 1.55 * 2))
                    src = rl.Rectangle(0, 0, float(icon.width), float(icon.height))
                    dst = rl.Rectangle(float(ix - isz // 2), float(iy - isz // 2),
                                       float(isz), float(isz))
                    alpha = 150 if looted else 255
                    rl.draw_texture_pro(icon, src, dst, rl.Vector2(0, 0), 0.0,
                                        rl.Color(255, 255, 255, alpha))
                else:
                    glyph = delve_gen.NODE_ICONS.get(node['type'], '?')
                    fs = max(10, int(34 * self.zoom))   # 2× — paired with the icons
                    gw = fonts.measure(glyph, fs)
                    fonts.draw(glyph, ix - gw // 2, iy - fs // 2 - 1, fs,
                               rl.Color(20, 20, 26, 255))

    def _draw_title(self, cw):
        # §9A-1: framed title banner, top-left
        pad = 14
        tw = fonts.measure(self.title, 22)
        rl.draw_rectangle(pad, pad, tw + 48, 44, _BANNER_BG)
        rl.draw_rectangle_lines(pad, pad, tw + 48, 44, rl.Color(0xE0, 0xE0, 0xE0, 255))
        fonts.draw(self.title, pad + 38, pad + 10, 22, rl.Color(0xE0, 0xE0, 0xE0, 255))
        try:
            from ui.icons import draw as _icon
            _icon('portal', pad + 10, pad + 12, 20, rl.Color(80, 200, 255, 255))
        except Exception:
            pass

    def _draw_best_depth(self, cw, below_title=False):
        """BEST DEPTH is drawn on the screen frame at the top-left, outside
        the modal. It is the depth record (never decreases), not the current
        node's depth, so retreating cannot lower it."""
        best = self._best_depth()
        label, value = 'BEST DEPTH', str(best)
        fs = 16
        pad = 12
        box_w = 150
        box_h = 34
        x, y = pad, pad if not below_title else pad + 52
        rl.draw_rectangle(x, y, box_w, box_h, _BANNER_BG)
        rl.draw_rectangle_lines(x, y, box_w, box_h, rl.Color(0xE0, 0xE0, 0xE0, 255))
        fonts.draw(label, x + 10, y + 10, 12, rl.Color(170, 175, 190, 230))
        vw = fonts.measure(value, fs)
        fonts.draw(value, x + box_w - vw - 12, y + 8, fs,
                   rl.Color(255, 220, 140, 255))

    def _draw_return_button(self, vw, vh):
        """Bottom-right RETURN TO HUB button; update() consumes the click and
        reports ('return_hub',). The rect is stored in canvas coords."""
        btn_w, btn_h = 170, 36
        bx, by = vw - btn_w - 12, vh - btn_h - 12
        rect = rl.Rectangle(float(bx), float(by), float(btn_w), float(btn_h))
        mx = rl.get_mouse_x() - self._ox
        my = rl.get_mouse_y() - self._oy
        hot = (0 <= mx < vw and 0 <= my < vh
               and rl.check_collision_point_rec(rl.Vector2(float(mx), float(my)),
                                                rect))
        rl.draw_rectangle(int(self._ox + bx), int(self._oy + by), btn_w, btn_h,
                          rl.Color(40, 26, 10, 220 if hot else 180))
        rl.draw_rectangle_lines(int(self._ox + bx), int(self._oy + by),
                                btn_w, btn_h, _TOOLTIP_BORDER)
        fonts.draw('RETURN TO HUB', int(self._ox + bx + btn_w // 2)
                   - fonts.measure('RETURN TO HUB', 13) // 2,
                   int(self._oy + by) + 12, 13, rl.Color(255, 235, 180, 255))
        self._return_btn = rect

    def _best_depth(self):
        """Depth record from the chart (monotonic), via the generator helper."""
        return delve_gen.chart_best_depth(self.chart or {})

    def _revealed_set(self):
        """Nodes visible through the fog: visited nodes plus every node
        directly adjacent (via chart edges) to a visited one. Deliberately
        ignores the stale state=='available' flags — those outlive the node
        that opened them and made far-off nodes look enterable."""
        if self.chart is None:
            return set()
        graph = self.chart['graph']
        visited = set(self.chart.get('visited', []))
        revealed = set(visited) | set(self.selectable_ids)
        for parent_id, child_id in graph['edges']:
            if parent_id in visited:
                revealed.add(child_id)
            if child_id in visited:
                revealed.add(parent_id)
        return revealed

    def _draw_depth_gauge(self, ch, graph):
        # §9A-4: right-edge vertical thermometer (current vs best depth)
        max_depth = max((n['depth'] for n in graph['nodes'].values()), default=1)
        best = self._best_depth()
        gauge_h = ch - 220
        gx, gy = rl.get_screen_width() - 30, 110
        rl.draw_rectangle(gx, gy, 14, gauge_h, rl.Color(0, 0, 0, 140))
        rl.draw_rectangle_lines(gx, gy, 14, gauge_h, rl.Color(0xE0, 0xE0, 0xE0, 180))
        fill = int(gauge_h * min(1.0, best / max(1, max_depth)))
        rl.draw_rectangle(gx + 2, gy + gauge_h - fill, 10, fill,
                          rl.Color(80, 200, 255, 230))
        # fracture-zone ticks every ZONE_PERIOD depths
        for depth in range(delve_gen.ZONE_PERIOD, max_depth + 1,
                           delve_gen.ZONE_PERIOD):
            ty = gy + int(gauge_h * (1.0 - depth / max(1, max_depth)))
            rl.draw_rectangle(gx - 4, ty, 6, 2, rl.Color(255, 255, 255, 160))

    def _draw_tooltip(self, vw, vh, graph):
        """PoE-style node tooltip: gold header (node title + zone), body
        with DEPTH / MONSTER LEVEL / CONTAINS + reward icon, and a single
        button_1 'ENTER' button for selectable nodes. Completed nodes show
        a placeholder in place of the reward icon."""
        self._tooltip_btn = None
        nid = self._hover_id
        if nid is None:
            return
        node = graph['nodes'].get(nid)
        if node is None:
            return
        looted = nid in self.chart.get('looted', [])
        known = nid in self._revealed_set()
        selectable = nid in self.selectable_ids

        title = node.get('loot') or node.get('label') or 'Delve Node'
        zone = delve_gen.zone_for_depth(node['depth'])

        # body lines (text, color) — icon rows handled specially below
        body = []
        reward = None            # (item_id, name, count, extra_count)
        if known:
            body.append((f"DEPTH: {node['depth']}", rl.Color(120, 200, 255, 255)))
            body.append((f"MONSTER LEVEL: {node['enemy_level']}",
                         rl.Color(255, 150, 120, 255)))
            rewards = node.get('rewards') or []
            if looted:
                body.append(('COMPLETED', rl.Color(140, 144, 158, 255)))
            elif rewards:
                r0 = rewards[0]
                name = self._item_name(r0['item'])
                extra = sum(r.get('count', 1) for r in rewards[1:])
                reward = (r0['item'], name, r0.get('count', 1), extra)
            if node['type'] == 'checkpoint':
                body.append(('Anima Cart — rest & refill flask',
                             rl.Color(255, 220, 140, 220)))
        else:
            body.append(('Undiscovered', rl.Color(140, 144, 158, 255)))
            body.append((f"DEPTH: {node['depth']}", rl.Color(90, 94, 108, 255)))

        fs, lh = 13, 20
        icon_px = 24
        btn_w, btn_h = 48, 54        # button_1 art (32x36) scaled 1.5x
        has_btn = selectable and known
        rlabel_txt = None
        if reward is not None:
            item_id, name, count, extra = reward
            rlabel_txt = f"{name} x{count}" if count > 1 else name
            if extra:
                rlabel_txt += f"  (+{extra})"
        head_w = max(fonts.measure(title, 15), fonts.measure(zone['name'], 11)) + 24
        body_w = max((fonts.measure(t, fs) for t, _ in body), default=0) + 20
        contains_w = ((icon_px + 8 + fonts.measure(rlabel_txt, fs) + 20)
                      if rlabel_txt else 0)
        tw = max(170, head_w, body_w, contains_w)
        header_h = 40
        body_h = (len(body) + (1 if rlabel_txt else 0)) * lh + 12
        if has_btn:
            body_h += btn_h - 10
        th = header_h + body_h
        mx, my = rl.get_mouse_x() - self._ox, rl.get_mouse_y() - self._oy
        tx = min(vw - tw - 8, mx + 16)
        ty = min(vh - th - 8, my + 8)
        tx = max(8, tx)
        ty = max(8, ty)
        px, py = self._ox + int(tx), self._oy + int(ty)

        # frame + body
        rl.draw_rectangle(px, py, int(tw), th, _TOOLTIP_BG)
        rl.draw_rectangle_lines(px, py, int(tw), th, _TOOLTIP_BORDER)
        # gold header bar
        rl.draw_rectangle(px + 1, py + 1, int(tw) - 2, header_h - 2, _HEADER_BG)
        fonts.draw(title, px + 10, py + 5, 15, rl.Color(255, 220, 140, 255))
        fonts.draw(zone['name'], px + 10, py + 23, 11,
                   rl.Color(*zone['accent'], 255))

        by = py + header_h + 6
        for j, (txt, clr) in enumerate(body):
            fonts.draw(txt, px + 10, by + j * lh, fs, clr)
        if rlabel_txt is not None:
            ry = by + len(body) * lh
            icon = _reward_icon(reward[0])
            if icon and icon.id > 0:
                src = rl.Rectangle(0, 0, float(icon.width), float(icon.height))
                dst = rl.Rectangle(float(px + tw - icon_px - 12), float(ry - 2),
                                   float(icon_px), float(icon_px))
                rl.draw_texture_pro(icon, src, dst, rl.Vector2(0, 0), 0.0,
                                    rl.WHITE)
            lw = fonts.measure(rlabel_txt, fs)
            fonts.draw(rlabel_txt, px + tw - icon_px - 12 - lw - 8, ry,
                       fs, rl.Color(190, 120, 255, 255))

        # ENTER button — drawn with button_1 art, rect stored in canvas
        # coords (update() consumes it; rendering adds the popup origin)
        if has_btn:
            bx = tx + tw - btn_w - 10
            bty = ty + th - btn_h - 8
            mx_c, my_c = mx, my
            pressed = (0 <= mx_c < vw and 0 <= my_c < vh
                       and rl.check_collision_point_rec(
                           rl.Vector2(float(mx_c), float(my_c)),
                           rl.Rectangle(float(bx), float(bty),
                                        float(btn_w), float(btn_h))))
            tex = _enter_button_tex(pressed=pressed)
            if tex and tex.id > 0:
                src = rl.Rectangle(0, 0, float(tex.width), float(tex.height))
                dst = rl.Rectangle(float(self._ox + bx), float(self._oy + bty),
                                   float(btn_w), float(btn_h))
                rl.draw_texture_pro(tex, src, dst, rl.Vector2(0, 0), 0.0,
                                    rl.WHITE)
            else:
                rl.draw_rectangle(self._ox + int(bx), self._oy + int(bty),
                                  btn_w, btn_h, rl.Color(20, 16, 8, 220))
                rl.draw_rectangle_lines(self._ox + int(bx), self._oy + int(bty),
                                        btn_w, btn_h, _TOOLTIP_BORDER)
            fonts.draw('ENTER', self._ox + int(bx) + 24
                       - fonts.measure('ENTER', 11) // 2,
                       self._oy + int(bty) + 20, 11, rl.Color(255, 235, 180, 255))
            self._tooltip_btn = (rl.Rectangle(float(bx), float(bty),
                                              float(btn_w), float(btn_h)), nid)

    @staticmethod
    def _item_name(item_id):
        try:
            from systems.items import ITEMS
            return (ITEMS.get(item_id) or {}).get('name', item_id)
        except Exception:
            return item_id
